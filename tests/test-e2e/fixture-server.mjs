/**
 * ImgFetch e2e — tests/test-e2e/fixture-server.mjs
 * Plain Node http server. Every page and asset is GENERATED by the test —
 * no internet needed. Serves:
 *  - /gallery      40 normal images + lazy (data-src) + srcset + <picture>
 *                    + CSS backgrounds + iframe + inline SVG
 *  - /gallery-big  600 images (bulk / worker-kill tests)
 *  - /tall?h=N     N-px article with sticky header + fixed cookie banner
 *  - /frame-imgs   5 images (loaded inside the gallery iframe)
 *  - /img/W/H/RRGGBB.png        generated PNG
 *  - /img/wrong-type.png        PNG bytes served as text/plain
 *  - /img/needs-referer.png     403 without Referer, PNG with it
 *  - /img/404.png, /img/429.png status codes
 *  - /img/slow.png              8 s delay then PNG
 *  - /img/big.png               ~30 MB PNG
 *  - /img/named/<name>.png      filename edge cases (Urdu, emoji, 200 chars)
 */
import http from 'node:http';
import zlib from 'node:zlib';

// --- minimal CRC32 + PNG writer (pure Node) ---
const CRC_T = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) c = CRC_T[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function pngChunk(type, data) {
  const td = Buffer.from(type, 'ascii');
  const b = Buffer.alloc(12 + data.length);
  b.writeUInt32BE(data.length, 0);
  td.copy(b, 4);
  data.copy(b, 8);
  b.writeUInt32BE(crc32(Buffer.concat([td, data])), 8 + data.length);
  return b;
}
export function makePng(w, h, [r, g, b]) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8; ihdr[9] = 2; // 8-bit truecolor
  const stride = w * 3 + 1;
  const raw = Buffer.alloc(stride * h);
  for (let y = 0; y < h; y += 1) {
    raw[y * stride] = 0;
    for (let x = 0; x < w; x += 1) {
      const o = y * stride + 1 + x * 3;
      // Slight vertical gradient so bands/tiles are detectable.
      const f = 0.7 + (0.3 * (y % 256)) / 256;
      raw[o] = Math.min(255, r * f) | 0;
      raw[o + 1] = Math.min(255, g * f) | 0;
      raw[o + 2] = Math.min(255, b * f) | 0;
    }
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', zlib.deflateSync(raw)),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}
function colorFor(i) {
  const palette = [[220, 60, 60], [60, 160, 220], [70, 180, 90], [230, 180, 50], [150, 90, 200]];
  return palette[i % palette.length];
}

const NAMED = [
  ['urdu', 'تصویر-نمبر-1'],
  ['emoji', 'pic-📸-🎉-test'],
  ['long', 'a'.repeat(200)],
  ['dots', '..%2F..%2Fevil'],
  ['spaces', 'my%20photo%201'],
];

function galleryHtml(big) {
  const n = big ? 600 : 40;
  let imgs = '';
  for (let i = 0; i < n; i += 1) {
    const w = 120 + ((i * 37) % 200);
    const h = 90 + ((i * 53) % 160);
    const c = colorFor(i).map((x) => x.toString(16).padStart(2, '0')).join('');
    imgs += `<img src="/img/${w}/${h}/${c}-${i}.png" width="${w}" height="${h}" alt="img${i}">\n`;
  }
  // Lazy images (data-src), srcset, <picture>, CSS background, iframe, inline SVG.
  const extra = `
<img data-src="/img/300/200/00ff00.png" class="lazy" width="300" height="200" alt="lazy1">
<img data-src="/img/320/210/0000ff.png" class="lazy" width="320" height="210" alt="lazy2">
<img srcset="/img/100/80/ff0000.png 1x, /img/200/160/ff0000.png 2x" src="/img/100/80/ff0000.png" width="100" height="80" alt="srcset1">
<picture><source srcset="/img/250/180/00ffff.png"><img src="/img/250/180/00ffff.png" width="250" height="180" alt="pic1"></picture>
<div class="bg" style="width:200px;height:120px;background-image:url(/img/200/120/ff00ff.png)"></div>
<iframe src="/frame-imgs" width="400" height="300"></iframe>
<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="green"/></svg>
<script>
// Reveal lazy images like a real lazy-loader would on scroll.
for (const im of document.querySelectorAll('img.lazy')) im.src = im.dataset.src;
</script>`;
  const named = NAMED.map(([k, nm]) => `<img src="/img/named/${nm}.png" width="50" height="50" alt="${k}">`).join('\n');
  return `<!DOCTYPE html><html><head><title>gallery</title>
<style>.sticky-note{position:sticky;top:0;background:#333;color:#fff;padding:8px}</style>
</head><body><div class="sticky-note">gallery fixture</div>${imgs}${big ? '' : extra}${named}</body></html>`;
}

function tallHtml(h) {
  let sections = '';
  const step = 1000;
  for (let y = 0; y < h; y += step) {
    const c = colorFor(y / step | 0).map((x) => x.toString(16).padStart(2, '0')).join('');
    sections += `<div style="height:${step}px;background:#${c};color:#fff;font-size:48px">section ${y / step}</div>\n`;
  }
  return `<!DOCTYPE html><html><head><title>tall</title></head><body style="margin:0">
<header style="position:sticky;top:0;height:60px;background:#111;color:#fff;z-index:5">STICKY HEADER</header>
${sections}
<div id="cookie" style="position:fixed;bottom:0;left:0;right:0;height:80px;background:#222;color:#fff;z-index:9">COOKIE BANNER <button>ok</button></div>
</body></html>`;
}

export function startFixtureServer(port = 0) {
  const server = http.createServer((req, res) => {
    const url = new URL(req.url, 'http://x');
    const p = url.pathname;
    const send = (code, type, body, headers = {}) => {
      res.writeHead(code, { 'content-type': type, ...headers });
      res.end(body);
    };
    if (p === '/gallery') return send(200, 'text/html', galleryHtml(false));
    if (p === '/favicon.ico') return send(204, 'image/x-icon', '');
    if (p === '/gallery-big') return send(200, 'text/html', galleryHtml(true));
    if (p === '/frame-imgs') {
      let s = '<!DOCTYPE html><html><body>';
      for (let i = 0; i < 5; i += 1) s += `<img src="/img/80/60/ff8800.png" width="80" height="60" alt="f${i}">`;
      return send(200, 'text/html', `${s}</body></html>`);
    }
    if (p === '/tall') {
      const h = Math.min(60000, Math.max(1000, parseInt(url.searchParams.get('h') || '25000', 10) || 25000));
      return send(200, 'text/html', tallHtml(h));
    }
    if (p === '/img/wrong-type.png') return send(200, 'text/plain', makePng(64, 64, [255, 0, 0]));
    if (p === '/img/needs-referer.png') {
      if (!req.headers.referer) return send(403, 'text/plain', 'referer required');
      return send(200, 'image/png', makePng(64, 64, [0, 255, 0]));
    }
    if (p === '/img/404.png') return send(404, 'text/plain', 'nope');
    if (p === '/img/429.png') return send(429, 'text/plain', 'slow down', { 'retry-after': '1' });
    if (p === '/img/slow.png') {
      setTimeout(() => send(200, 'image/png', makePng(64, 64, [0, 0, 255])), 8000);
      return;
    }
    if (p === '/img/big.png') {
      // ~30 MB of incompressible PNG data.
      const raw = zlib.deflateSync(Buffer.alloc(0));
      const w = 3000; const h = 2600;
      const stride = w * 3 + 1;
      const px = Buffer.allocUnsafe(stride * h);
      for (let i = 0; i < px.length; i += 1) px[i] = (Math.random() * 256) | 0;
      for (let y = 0; y < h; y += 1) px[y * stride] = 0;
      const body = Buffer.concat([
        Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
        pngChunk('IHDR', (() => { const b = Buffer.alloc(13); b.writeUInt32BE(w, 0); b.writeUInt32BE(h, 4); b[8] = 8; b[9] = 2; return b; })()),
        pngChunk('IDAT', zlib.deflateSync(px)),
        pngChunk('IEND', Buffer.alloc(0)),
      ]);
      return send(200, 'image/png', body);
    }
    let m = p.match(/^\/img\/(\d{1,4})\/(\d{1,4})\/([0-9a-f]{6})(?:-(\d+))?\.png$/i);
    if (m) {
      const w = Math.min(1200, +m[1]); const hh = Math.min(1200, +m[2]);
      const rgb = [parseInt(m[3].slice(0, 2), 16), parseInt(m[3].slice(2, 4), 16), parseInt(m[3].slice(4, 6), 16)];
      return send(200, 'image/png', makePng(w, hh, rgb), { 'cache-control': 'no-store' });
    }
    m = p.match(/^\/img\/named\/(.+)\.png$/);
    if (m) return send(200, 'image/png', makePng(50, 50, [128, 128, 0]));
    send(404, 'text/plain', 'fixture 404');
  });
  return new Promise((resolve) => {
    server.listen(port, '127.0.0.1', () => resolve({ server, port: server.address().port }));
  });
}

// Allow `node fixture-server.mjs` to run it standalone for debugging.
if (process.argv[1] && process.argv[1].endsWith('fixture-server.mjs')) {
  const { port } = await startFixtureServer(8765);
  console.log(`fixture server on http://127.0.0.1:${port}`);
}
